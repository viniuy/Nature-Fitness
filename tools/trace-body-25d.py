import cv2, numpy as np, json
D = '/tmp/claude-0/r25/'; APP = '/home/user/nature-fitness/'
GROUPS = ['chest','frontDelts','sideDelts','rearDelts','traps','lats','upperBack','lowerBack','biceps','triceps','forearms','abs','obliques','glutes','quads','hamstrings','adductors','calves']
def rd(p): return cv2.imread(D + p, cv2.IMREAD_UNCHANGED)
def smooth(mask, r=2.0):
    b = cv2.GaussianBlur(mask.astype(np.float32), (0, 0), r); return b > 0.5
def clean(mask, minarea):
    m = mask.astype(np.uint8)
    m = cv2.morphologyEx(m, cv2.MORPH_CLOSE, cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (7, 7)))
    m = cv2.morphologyEx(m, cv2.MORPH_OPEN, cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (3, 3)))
    n, lab, st, _ = cv2.connectedComponentsWithStats(m, 8)
    out = np.zeros_like(m)
    for i in range(1, n):
        if st[i, cv2.CC_STAT_AREA] >= minarea: out[lab == i] = 1
    # fill small holes
    inv = 1 - out; n, lab, st, _ = cv2.connectedComponentsWithStats(inv, 4)
    for i in range(1, n):
        if st[i, cv2.CC_STAT_AREA] < 60: out[lab == i] = 1
    return smooth(out, 1.5)
def path(mask, eps=0.7):
    cs, _ = cv2.findContours(mask.astype(np.uint8), cv2.RETR_CCOMP, cv2.CHAIN_APPROX_NONE)
    parts = []
    for c in cs:
        if cv2.contourArea(c) < 20: continue
        a = cv2.approxPolyDP(c, eps, True).reshape(-1, 2)
        if len(a) < 3: continue
        parts.append('M' + 'L'.join(f'{x} {y}' for x, y in a) + 'Z')
    return ''.join(parts)
out = {}
SKIP = {'front': {'rearDelts', 'upperBack', 'lowerBack', 'glutes', 'hamstrings'}, 'back': {'chest', 'abs', 'frontDelts', 'biceps'}}
for view in ('front', 'back'):
    A = rd(f'id-{view}-a.png'); B = rd(f'id-{view}-b.png')
    aa = A[..., 3] > 128; ba = B[..., 3] > 128
    r = A[..., 2].astype(int)
    sil = smooth(clean(aa | ba, 400), 1.5)
    groups = {}; masks = {}; skipped = np.zeros_like(aa)
    for i, g in enumerate(GROUPS):
        lin = ((i + 1) * 12 / 255) ** 2.2
        v = round(255 * (12.92 * lin if lin <= 0.0031308 else 1.055 * lin ** (1 / 2.4) - 0.055))
        m = aa & (np.abs(r - v) <= 2)
        if g in SKIP[view]: skipped |= m; continue
        m = clean(m, 120) & sil
        if m.sum() < 200: print('drop', view, g, m.sum()); continue
        masks[g] = m
    # pixels of muscles hidden on this side go to the neighbouring visible group
    k = cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (15, 15))
    taken = np.zeros_like(aa)
    for g, m in masks.items(): taken |= m
    for g, m in sorted(masks.items(), key=lambda kv: kv[0] != 'abs'):
        grow = cv2.dilate(m.astype(np.uint8), k).astype(bool) & skipped & ~taken
        masks[g] = smooth(clean(m | grow, 120), 1.0) & sil; taken |= grow
    for g, m in masks.items(): groups[g] = path(m)
    out[view] = {'outline': path(sil, 0.8), 'groups': groups}
    # shading: A where present else B, white outside
    SA = rd(f'shade-{view}-a.png'); SB = rd(f'shade-{view}-b.png')
    ga = cv2.cvtColor(SA[..., :3], cv2.COLOR_BGR2GRAY).astype(np.float32)
    gb = cv2.cvtColor(SB[..., :3], cv2.COLOR_BGR2GRAY).astype(np.float32)
    g = np.where(aa & ~skipped, ga, np.where(ba, gb, 255))
    fig = g[sil]; hi = np.percentile(fig, 97); lo = np.percentile(fig, 2)
    t = np.clip((g - lo) / max(1, hi - lo), 0, 1)
    shade = 0.5 + 0.5 * t ** 0.9  # 0.5..1 multiply
    shade[~sil] = 1
    cv2.imwrite(APP + f'public/body/shade-{view}.webp', (shade * 255).astype(np.uint8), [cv2.IMWRITE_WEBP_QUALITY, 82])
    print(view, sorted(groups), {k: len(v) for k, v in groups.items()})
h, w = A.shape[:2]
ts = "// Generated by tools/trace-body-25d.py from the Z-Anatomy model (CC BY-SA 4.0). Do not edit.\n"
ts += "import type { Muscle } from './ranks';\n"
ts += "export interface BodyView { outline: string; groups: Partial<Record<Muscle, string>> }\n"
ts += f"export const BODY_W = {w};\nexport const BODY_H = {h};\n"
ts += f"export const BODY_VIEWS: Record<'front' | 'back', BodyView> = {json.dumps(out)};\n"
open(APP + 'src/lib/body25d.ts', 'w').write(ts)
print(w, h, len(ts))
